/** A photo's address at about `width` pixels wide: the 1400px copy for banners and big gallery photos, else 640px. */
export function photoUrl(p, width = 1200) {
  if (!p) return "";
  return asset(`${p.src}-${width > 700 ? 1400 : 640}.webp`);
}

/** Adds photos: { banner, gallery } to each example business that has photos in examplePhotos. */
export function withPhotos(list) {
  return list.map((b) => {
    const keys = (examplePhotos[b.id] || []).filter((k) => photos[k]);
    if (b.photos || !keys.length) return b;
    return { ...b, photos: { banner: keys[0], gallery: keys.slice(1) } };
  });
}

/** Every photo key a listing has: banner first, then the gallery. */
export const allPhotos = (b) => [b.photos?.banner, ...(b.photos?.gallery || [])].filter((k) => photos[k]);
